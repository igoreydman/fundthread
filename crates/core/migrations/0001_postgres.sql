-- One organization/workspace per database. All application objects use this schema.
CREATE TABLE workspace (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    organization text NOT NULL CHECK (length(btrim(organization)) BETWEEN 1 AND 4000),
    operator_name text NOT NULL CHECK (length(btrim(operator_name)) BETWEEN 1 AND 4000),
    currency text NOT NULL DEFAULT 'USD' CHECK (currency = 'USD')
);
CREATE TABLE documents (
    id text PRIMARY KEY,
    filename text NOT NULL,
    mime text NOT NULL CHECK (mime IN ('application/pdf','image/png','image/jpeg')),
    hash text NOT NULL UNIQUE CHECK (hash ~ '^[0-9a-f]{64}$'),
    bytes bytea NOT NULL CHECK (octet_length(bytes) BETWEEN 1 AND 20971520)
);
CREATE TABLE funds (
    id text PRIMARY KEY,
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 4000),
    code text NOT NULL UNIQUE CHECK (length(btrim(code)) BETWEEN 1 AND 4000),
    budget bigint NOT NULL CHECK (budget BETWEEN 0 AND 1000000000000000),
    period_start date NOT NULL,
    period_end date NOT NULL CHECK (period_end >= period_start),
    restrictions text NOT NULL
);
CREATE TABLE fund_categories (
    fund_id text NOT NULL REFERENCES funds(id),
    category text NOT NULL CHECK (length(btrim(category)) BETWEEN 1 AND 4000),
    PRIMARY KEY (fund_id, category)
);
CREATE TABLE expenses (
    id text PRIMARY KEY,
    document_id text NOT NULL UNIQUE REFERENCES documents(id),
    current_revision bigint NOT NULL DEFAULT 0 CHECK (current_revision >= 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE reviews (
    expense_id text NOT NULL REFERENCES expenses(id),
    revision bigint NOT NULL CHECK (revision >= 0),
    merchant text NOT NULL DEFAULT '',
    claimant text NOT NULL DEFAULT '',
    purpose text NOT NULL DEFAULT '',
    expense_date date,
    category text NOT NULL DEFAULT 'Workshop supplies',
    total bigint NOT NULL CHECK (total BETWEEN 0 AND 1000000000000000) DEFAULT 0,
    eligible bigint NOT NULL CHECK (eligible BETWEEN 0 AND 1000000000000000) DEFAULT 0 CHECK (eligible <= total),
    reviewed boolean NOT NULL DEFAULT false,
    at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (expense_id, revision),
    CHECK (NOT reviewed OR (expense_date IS NOT NULL AND eligible > 0
        AND length(btrim(merchant)) > 0 AND length(btrim(claimant)) > 0
        AND length(btrim(purpose)) > 0 AND length(btrim(category)) > 0))
);
ALTER TABLE expenses ADD CONSTRAINT current_review_fk
    FOREIGN KEY (id,current_revision) REFERENCES reviews(expense_id,revision)
    DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE review_allocations (
    expense_id text NOT NULL,
    revision bigint NOT NULL,
    fund_id text NOT NULL REFERENCES funds(id),
    amount bigint NOT NULL CHECK (amount BETWEEN 0 AND 1000000000000000),
    PRIMARY KEY (expense_id,revision,fund_id),
    FOREIGN KEY (expense_id,revision) REFERENCES reviews(expense_id,revision)
);
CREATE TABLE approvals (
    expense_id text NOT NULL,
    revision bigint NOT NULL,
    approver text NOT NULL CHECK (length(btrim(approver)) BETWEEN 1 AND 4000),
    reference text NOT NULL CHECK (length(btrim(reference)) BETWEEN 1 AND 4000),
    at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (expense_id,revision),
    FOREIGN KEY (expense_id,revision) REFERENCES reviews(expense_id,revision)
);
CREATE TABLE payments (
    id text PRIMARY KEY,
    expense_id text NOT NULL REFERENCES expenses(id),
    amount bigint NOT NULL CHECK (amount BETWEEN 0 AND 1000000000000000) CHECK (amount > 0),
    reference text NOT NULL CHECK (length(btrim(reference)) BETWEEN 1 AND 4000),
    payment_date date NOT NULL,
    reconciled boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (expense_id,reference)
);
CREATE TABLE extraction_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id text NOT NULL REFERENCES expenses(id),
    payload jsonb NOT NULL CHECK (octet_length(payload::text) <= 2000000),
    at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE privacy_regions (
    document_id text NOT NULL REFERENCES documents(id),
    ordinal integer NOT NULL CHECK (ordinal BETWEEN 0 AND 999),
    page integer NOT NULL CHECK (page BETWEEN 1 AND 100),
    x double precision NOT NULL CHECK (x >= 0 AND x < 1),
    y double precision NOT NULL CHECK (y >= 0 AND y < 1),
    w double precision NOT NULL CHECK (w > 0 AND w <= 1),
    h double precision NOT NULL CHECK (h > 0 AND h <= 1),
    PRIMARY KEY (document_id,ordinal),
    CHECK (x+w <= 1.000001 AND y+h <= 1.000001)
);
CREATE TABLE events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id text NOT NULL,
    action text NOT NULL,
    detail text NOT NULL,
    at timestamptz NOT NULL DEFAULT clock_timestamp()
);
-- PK and UNIQUE indexes already cover hash, code, expense/document lookup,
-- expense payments, current review, review history, and document mask reads.
CREATE INDEX expenses_created_idx ON expenses (created_at DESC,id);
CREATE INDEX funds_name_idx ON funds (name,id);
CREATE INDEX allocations_fund_idx ON review_allocations (fund_id,expense_id,revision) INCLUDE (amount);
CREATE INDEX payments_created_idx ON payments (created_at DESC,id);
CREATE INDEX extractions_expense_latest_idx ON extraction_runs (expense_id,id DESC);
